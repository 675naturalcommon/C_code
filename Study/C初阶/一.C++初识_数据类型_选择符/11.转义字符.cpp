#include<iostream>
using namespace std;
int main()
{
    //转义字符

    //1.换行符  \n
    cout << "Hello world" <<endl;
    cout <<"Hello world\n";
    /*2.反斜杠  \\  */
    cout << "\\" <<endl;
    //3.水平制表符  \t
    cout << "aaa\t" << "Hello World" << endl;
    cout << "aaaaaaaa" <<endl;
    system("pause");
    return 0;
}